package com.example.data

object HadithData {

    data class Hadith(
        val collection: String,
        val id: String,
        val number: String,
        val arabic: String,
        val english: String,
        val reference: String
    )

    data class BookHadith(
        val id: String,
        val bookId: String,
        val chapterId: String,
        val chapterTitle: String,
        val numberInBook: String,
        val globalNumber: String,
        val narrator: String,
        val arabicText: String,
        val explanation: String,
        val reference: String
    )

    data class HadithChapter(
        val id: String,
        val number: Int,
        val title: String,
        val description: String = "",
        val hadiths: List<BookHadith>
    )

    data class HadithBook(
        val id: String,
        val title: String,
        val fullTitle: String,
        val author: String,
        val authorFullName: String,
        val deathYear: String,
        val category: String, // "الصحيحان", "السنن الأربعة", "المسانيد والموطآت", "الجوامع والآداب"
        val totalHadithsDesc: String,
        val availableContentDesc: String,
        val isFullyBundled: Boolean,
        val verifiedSource: String,
        val introduction: String,
        val primaryColorHex: Long,
        val secondaryColorHex: Long,
        val accentGoldHex: Long = 0xFFD4AF37,
        val chapters: List<HadithChapter>
    ) {
        val totalAvailableHadiths: Int
            get() = chapters.sumOf { it.hadiths.size }

        val allHadiths: List<BookHadith>
            get() = chapters.flatMap { it.hadiths }
    }

