    private fun normalize(value: String): String {
        val decomposed = Normalizer.normalize(value.lowercase(Locale.ROOT), Normalizer.Form.NFD)
        return decomposed.replace(Regex("\\p{Mn}+"), "")
            .replace(Regex("[\\u064B-\\u065F\\u0670\\u06D6-\\u06ED]"), "")
            .replace('أ', 'ا').replace('إ', 'ا').replace('آ', 'ا').replace('ى', 'ي')
            .replace(Regex("[^\\p{L}\\p{N}\\s]"), " ")
            .replace(Regex("\\s+"), " ").trim()
    }

    fun answer(question: String): String? {
        val q = normalize(question)
        if (q.isBlank()) return null
        if (containsAny(q, listOf("اباحي", "اباحيه", "مقاطع جنسيه", "صور عاريه", "افلام جنسيه",
                "وصف جنسي صريح", "بورنو", "porn"))) {
            return "مِشكاة مخصص للمعرفة الإسلامية، ولا يقدّم محتوى إباحيًا أو أوصافًا جنسية صريحة. إذا كان سؤالك عن حكم شرعي أو مسألة زوجية جادة، فصغه بصورة علمية محترمة وسأبحث عن معلومات مناسبة من مصادر موثوقة."
        }
        if (isClearlyOutsideIslamicScope(q)) {
            return "أنا مِشكاة، مساعد متخصص في المعرفة الإسلامية. أستطيع مساعدتك في القرآن الكريم وتفسيره، وقصص الأنبياء، والسيرة النبوية، والحديث، والعقيدة، والفقه، والأذكار والتاريخ الإسلامي."
        }
        prophetAnswer(q)?.let { return it }
        islamicBasicsAnswer(q)?.let { return it }
        if (q.startsWith("من هو ") || q.startsWith("من هي ") || q.startsWith("من هم ") ||
            q.startsWith("عرفني على ")) {
            return "لم أجد في قاعدة مِشكاة الحالية إجابة محررة وموثقة لهذا السؤال. لا أريد أن أخمّن أو أنسب معلومة دينية بلا مرجع. ستُضاف إجابات موثقة إلى المكتبة تدريجيًا."
        }
        return null
    }

