        containsAny(q, listOf("افضل هاتف", "مواصفات هاتف", "سعر الهاتف", "كرة القدم",
            "نتيجة المباراة", "برمجة", "اكتب لي كود", "تطبيق اندرويد", "اسهم البورصة",
            "سعر الذهب اليوم", "طقس اليوم", "وصفة طبخ", "افضل سيارة", "اخبار السياسة"))

    private fun containsAny(value: String, phrases: List<String>): Boolean =
        phrases.any { normalize(it).let(value::contains) }

